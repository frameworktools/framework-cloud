// Run with PLAYWRIGHT_MODULE=/path/to/playwright/index.mjs node tests/js/artifact-reader.browser.mjs.
// Renders the actual Blade component and mounts its module in a real browser without a server.
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';

const playwright = process.env.PLAYWRIGHT_MODULE;
if (!playwright) throw new Error('Set PLAYWRIGHT_MODULE to an installed Playwright index.mjs.');
const { chromium } = await import(pathToFileURL(playwright).href);
const script = await readFile(new URL('../../resources/js/artifact-reader.js', import.meta.url), 'utf8');
const payload = '</script><script>window.artifactXss = true</script><img src=x onerror="window.artifactXss=true"> & "quoted"';
const rows = [['ten', 10.123456789], ['two', 2], ['missing', null], ['negative', -3], [payload, 4], ['same estimate', 2], ...Array.from({ length: 60 }, (_, index) => [`extra ${index}`, 100 + index])];
const table = { title: payload, columns: [{ name: 'term', type: 'string' }, { name: 'estimate', type: 'number' }], rows, row_count: rows.length };
const php = String.raw`require 'vendor/autoload.php'; $app = require 'bootstrap/app.php'; $app->make(Illuminate\Contracts\Console\Kernel::class)->bootstrap(); $table=json_decode(stream_get_contents(STDIN),true); echo view('components.artifact-table',['table'=>$table,'id'=>'browser-table'])->render();`;
const rendered = spawnSync('php', ['-r', php], { input: JSON.stringify(table), encoding: 'utf8', cwd: new URL('../..', import.meta.url) });
assert.equal(rendered.status, 0, rendered.stderr);
const browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL || 'chrome', headless: true });
try {
    const page = await browser.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.setContent(`<html><body>${rendered.stdout}</body></html>`);
    assert.equal(await page.locator('tbody tr').count(), 25, 'SSR fallback displays first page');
    assert.equal(await page.evaluate(() => window.artifactXss), undefined);
    await page.addScriptTag({ type: 'module', content: script });
    await page.waitForFunction(() => document.querySelector('[data-table-status]').textContent.includes('page 1'));
    const visibleTerms = () => page.locator('tbody tr td:first-child').allTextContents();
    const numericCell = page.locator('tbody tr').filter({ has: page.locator('td:first-child', { hasText: /^ten$/ }) }).locator('td').nth(1);
    assert.equal(await numericCell.innerText(), '10.123');
    assert.equal(await numericCell.getAttribute('title'), '10.123456789');
    const precisionInput = page.locator('[data-table-precision]');
    assert.equal(await precisionInput.getAttribute('type'), 'number');
    await precisionInput.fill('5');
    assert.equal(await numericCell.innerText(), '10.12346');
    await precisionInput.press('ArrowUp');
    assert.equal(await numericCell.innerText(), '10.123457');
    await precisionInput.press('ArrowDown');
    assert.equal(await numericCell.innerText(), '10.12346');
    await precisionInput.fill('3');
    assert.equal(await numericCell.innerText(), '10.123');
    await page.getByRole('button', { name: 'Increase decimal places', exact: true }).click();
    assert.equal(await numericCell.innerText(), '10.1235');
    await page.getByRole('button', { name: 'Decrease decimal places', exact: true }).click();
    assert.equal(await numericCell.innerText(), '10.123');

    assert.equal(await page.locator('[data-table-search]').isVisible(), true);
    assert.equal(await page.locator('[data-table-previous]').isDisabled(), true);
    await page.locator('[data-table-sort="1"]').click();
    assert.deepEqual((await visibleTerms()).slice(0, 5), ['negative', 'two', 'same estimate', payload, 'ten']);
    assert.equal(await page.locator('th').nth(1).getAttribute('aria-sort'), 'ascending');
    await page.locator('[data-table-size]').selectOption('250');
    assert.equal((await visibleTerms()).at(-1), 'missing', 'null stays last ascending');
    await page.locator('[data-table-sort="1"]').click();
    assert.equal((await visibleTerms()).at(-1), 'missing', 'null stays last descending');
    assert.deepEqual((await visibleTerms()).slice(-6), ['ten', payload, 'two', 'same estimate', 'negative', 'missing']);
    assert.equal(await page.locator('th').nth(1).getAttribute('aria-sort'), 'descending');
    await page.locator('[data-table-search]').fill('TWO');
    assert.deepEqual(await visibleTerms(), ['two']);
    await page.locator('[data-table-search]').fill('does not exist');
    assert.equal(await page.locator('tbody').innerText(), 'No matching rows.');
    assert.equal(await page.locator('[data-table-next]').isDisabled(), true);
    await page.locator('[data-table-search]').fill('');
    await page.locator('[data-table-size]').selectOption('25');
    await page.locator('[data-table-next]').click();
    assert.match(await page.locator('[data-table-status]').innerText(), /26–50 of 66 rows · page 2 of 3/);
    await page.locator('[data-table-next]').click();
    assert.equal(await page.locator('tbody tr').count(), 16);
    assert.equal(await page.locator('[data-table-next]').isDisabled(), true);
    await page.locator('[data-table-previous]').click();
    assert.equal(await page.locator('tbody tr').count(), 25);
    await page.locator('[data-table-size]').selectOption('50');
    assert.match(await page.locator('[data-table-status]').innerText(), /1–50 of 66 rows · page 1 of 2/);
    await page.locator('[data-table-search]').fill('</script>');
    assert.deepEqual(await visibleTerms(), [payload]);
    assert.equal(await page.locator('tbody img, tbody script').count(), 0);
    assert.equal(await page.evaluate(() => window.artifactXss), undefined);
    const downloadPending = page.waitForEvent('download');
    await page.locator('[data-table-export]').click();
    const download = await downloadPending;
    assert.equal(download.suggestedFilename(), 'table-preview.csv');
    const chunks = [];
    for await (const chunk of await download.createReadStream()) chunks.push(chunk);
    const csv = Buffer.concat(chunks).toString('utf8');
    assert.ok(csv.includes(payload.replaceAll('"', '""')), 'CSV contains escaped literal text');
    assert.ok(!csv.includes('extra 0'), 'CSV export respects the current search');
    assert.deepEqual(errors, []);
    await page.locator('[data-table-sort="0"]').focus();
    await page.keyboard.press('Enter');
    assert.equal(await page.locator('th').nth(0).getAttribute('aria-sort'), 'ascending');
    console.log('Real browser checks passed: numeric/stable/null sorting, search, paging, page size, keyboard sorting, ARIA state, SSR fallback, CSV export of filtered data, and escaped script/HTML payloads.');
} finally {
    await browser.close();
}
