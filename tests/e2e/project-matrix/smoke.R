args <- commandArgs(trailingOnly = TRUE)
setwd(args[[1]])
library(framework)
scaffold()
if (file.exists(".e2e-functions")) stopifnot(smoke_double(3) == 6)
spec <- jsonlite::read_json(".framework/spec.json", simplifyVector = FALSE)
dirs <- spec$directories
choices <- c(dirs$inputs_private_raw, dirs$inputs_raw, dirs$data)
data_dir <- if (length(choices)) choices[[1]] else "smoke-data"
dir.create(data_dir, recursive = TRUE, showWarnings = FALSE)
frame <- data.frame(x = 1:5, y = 1 + 2 * (1:5))
input <- file.path(data_dir, "smoke.csv")
data_save(frame, input, force = TRUE)
loaded <- data_read(input)
stopifnot(nrow(loaded) == 5, all(loaded$y == frame$y))
model <- lm(y ~ x, data = loaded)
stopifnot(abs(coef(model)[[2]] - 2) < 1e-8)
summary <- data.frame(rows = nrow(loaded), slope = unname(coef(model)[[2]]))
table_path <- save_table(summary, name = "smoke-summary")
model_path <- save_model(model, name = "smoke-model")
plot <- ggplot2::ggplot(loaded, ggplot2::aes(x, y)) + ggplot2::geom_point() + ggplot2::theme_minimal()
figure_path <- save_figure(plot, name = "smoke-figure", width = 4, height = 3)
cache("smoke-result", list(slope = 2))
stopifnot(cache_get("smoke-result")$slope == 2)
stopifnot(file.exists(table_path), file.exists(model_path), file.exists(figure_path), file.exists("framework.db"))
jsonlite::write_json(list(input = input, table = table_path, model = model_path, figure = figure_path, rows = 5, slope = 2, cache = TRUE), "smoke-result.json", auto_unbox = TRUE)
